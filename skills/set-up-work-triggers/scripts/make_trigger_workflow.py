#!/usr/bin/env python3
"""Generate a GitHub Actions workflow that starts a run from a label, a comment command, or a schedule.

Untrusted event fields (comment body, issue title, labels) are passed to steps only through env:,
never interpolated into run: scripts. A running label plus a concurrency group block double starts.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

DEFAULT_RUN_COMMAND = 'echo "replace with your run command"'
DEFAULT_NAME = "agent-run"
DEFAULT_RUNNING_LABEL = "running"
ALLOWED_ASSOCIATIONS = ("OWNER", "MEMBER", "COLLABORATOR")

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")
TRIGGER_LABEL_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._:/-]{0,49}$")
RUNNING_LABEL_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,49}$")
COMMAND_RE = re.compile(r"^/[A-Za-z0-9][A-Za-z0-9_-]{0,31}$")
CRON_FIELD_RE = re.compile(r"^[A-Za-z0-9*/,\-]+$")

# Event fields an outside user can control. They must never appear inside a run: block.
UNTRUSTED_FIELDS = (
    "github.event.comment.body",
    "github.event.issue.title",
    "github.event.issue.body",
    "github.event.pull_request.title",
    "github.event.pull_request.body",
    "github.event.pull_request.head.ref",
    "github.event.label.name",
    "github.head_ref",
)


class UsageError(Exception):
    pass


def validate(args: argparse.Namespace) -> None:
    if not NAME_RE.match(args.name):
        raise UsageError(f"--name must be lowercase kebab-case: {args.name!r}")
    if not (args.label or args.command or args.cron):
        raise UsageError("give at least one trigger: --label, --command, or --cron")
    if args.label and not TRIGGER_LABEL_RE.match(args.label):
        raise UsageError(f"--label has unsupported characters: {args.label!r}")
    if args.command and not COMMAND_RE.match(args.command):
        raise UsageError(f"--command must look like /run (letters, digits, - or _): {args.command!r}")
    if not RUNNING_LABEL_RE.match(args.running_label):
        raise UsageError(f"--running-label has unsupported characters: {args.running_label!r}")
    if args.label and args.label == args.running_label:
        raise UsageError("--label and --running-label must differ")
    for cron in args.cron:
        fields = cron.split()
        if len(fields) != 5 or not all(CRON_FIELD_RE.match(f) for f in fields):
            raise UsageError(f"--cron must have 5 fields: {cron!r}")
    if "${{" in args.run_command:
        raise UsageError("--run-command must not contain ${{ }} expressions; read values from env vars instead")
    if "\n" in args.run_command or "\r" in args.run_command:
        raise UsageError("--run-command must be one line; point it at a script for multi-step runs")


def yq(value: str) -> str:
    """Quote a string as a YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(value, ensure_ascii=True)


def build_workflow(
    name: str,
    label: str | None,
    command: str | None,
    crons: list[str],
    run_command: str,
    running_label: str,
    timeout_minutes: int,
) -> str:
    has_issue = bool(label or command)
    out: list[str] = []
    w = out.append

    w("# Generated by parstack set-up-work-triggers. Edit the run command, not the guard.")
    w(f"name: {name}")
    w("")
    w("on:")
    if label:
        w("  issues:")
        w("    types: [labeled]")
    if command:
        w("  issue_comment:")
        w("    types: [created]")
    if crons:
        w("  schedule:")
        for cron in crons:
            w(f"    - cron: {yq(cron)}")
    w("")
    w("permissions: {}")
    w("")
    w("concurrency:")
    w("  group: ${{ github.workflow }}-${{ github.event.issue.number || 'scheduled' }}")
    w("  cancel-in-progress: false")
    w("")
    w("jobs:")
    w("  run:")

    conditions = []
    if label:
        conditions.append(
            f"(github.event_name == 'issues' && github.event.label.name == '{label}')"
        )
    if command:
        conditions.append(
            "(github.event_name == 'issue_comment'"
            f" && (github.event.comment.body == '{command}' || startsWith(github.event.comment.body, '{command} '))"
            f" && contains(fromJSON('{json.dumps(list(ALLOWED_ASSOCIATIONS))}'), github.event.comment.author_association))"
        )
    if crons:
        conditions.append("github.event_name == 'schedule'")
    w("    if: >-")
    for i, cond in enumerate(conditions):
        suffix = " ||" if i < len(conditions) - 1 else ""
        w(f"      {cond}{suffix}")

    w("    runs-on: ubuntu-latest")
    w(f"    timeout-minutes: {timeout_minutes}")
    w("    permissions:")
    w("      contents: read")
    if has_issue:
        w("      issues: write")
    if command:
        w("      pull-requests: write")
    w("    steps:")
    w("      - uses: actions/checkout@v4")
    w("        with:")
    w("          persist-credentials: false")

    if has_issue:
        w("")
        w("      - name: Guard against double start")
        w("        id: guard")
        w("        if: github.event_name != 'schedule'")
        w("        env:")
        w("          GH_TOKEN: ${{ github.token }}")
        w("          REPO: ${{ github.repository }}")
        w("          NUMBER: ${{ github.event.issue.number }}")
        w(f"          RUNNING_LABEL: {yq(running_label)}")
        w("        run: |")
        w('          labels="$(gh api "repos/$REPO/issues/$NUMBER/labels" --jq \'.[].name\')"')
        w('          if printf \'%s\\n\' "$labels" | grep -Fxq "$RUNNING_LABEL"; then')
        w('            echo "Already running on #$NUMBER; skipping."')
        w('            echo "acquired=false" >> "$GITHUB_OUTPUT"')
        w("            exit 0")
        w("          fi")
        w('          gh api -X POST "repos/$REPO/issues/$NUMBER/labels" -f "labels[]=$RUNNING_LABEL" > /dev/null')
        w('          echo "acquired=true" >> "$GITHUB_OUTPUT"')

    w("")
    w("      - name: Run")
    if has_issue:
        w("        if: github.event_name == 'schedule' || steps.guard.outputs.acquired == 'true'")
    w("        env:")
    w(f"          RUN_COMMAND: {yq(run_command)}")
    w("          EVENT_NAME: ${{ github.event_name }}")
    if has_issue:
        w("          ISSUE_NUMBER: ${{ github.event.issue.number }}")
        w("          ISSUE_TITLE: ${{ github.event.issue.title }}")
    if command:
        w("          COMMENT_BODY: ${{ github.event.comment.body }}")
    w("        run: bash -c \"$RUN_COMMAND\"")

    if has_issue:
        w("")
        w("      - name: Release running label")
        w("        if: always() && steps.guard.outputs.acquired == 'true'")
        w("        env:")
        w("          GH_TOKEN: ${{ github.token }}")
        w("          REPO: ${{ github.repository }}")
        w("          NUMBER: ${{ github.event.issue.number }}")
        w(f"          RUNNING_LABEL: {yq(running_label)}")
        w('        run: gh api -X DELETE "repos/$REPO/issues/$NUMBER/labels/$RUNNING_LABEL" > /dev/null')

    return "\n".join(out) + "\n"


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def lint_workflow(text: str) -> list[str]:
    """Return script-injection problems: ${{ }} inside run: scripts, or untrusted fields outside env:/if:."""
    problems: list[str] = []
    lines = text.splitlines()
    run_indent: int | None = None  # indent of the active `run:` key when inside a block scalar
    for no, line in enumerate(lines, 1):
        stripped = line.strip()
        if run_indent is not None:
            if stripped and _indent(line) <= run_indent:
                run_indent = None
            else:
                if "${{" in line:
                    problems.append(f"line {no}: expression inside run: script")
                continue
        if stripped.startswith("#") or not stripped:
            continue
        key = stripped.lstrip("- ").split(":", 1)[0]
        if key == "run":
            value = stripped.split(":", 1)[1].strip() if ":" in stripped else ""
            if value.startswith(("|", ">")):
                run_indent = _indent(line) if not stripped.startswith("-") else _indent(line) + 2
            elif "${{" in value:
                problems.append(f"line {no}: expression inside run: script")
            continue
        for field in UNTRUSTED_FIELDS:
            if field in line and not _is_env_or_if(lines, no - 1):
                problems.append(f"line {no}: untrusted {field} outside env:/if:")
    return problems


def _is_env_or_if(lines: list[str], idx: int) -> bool:
    """True if line idx is an if: expression or a direct child of an env: mapping."""
    line = lines[idx]
    ind = _indent(line)
    if line.strip().lstrip("- ").startswith("if:"):
        return True
    # Walk up to the nearest less-indented key.
    for j in range(idx - 1, -1, -1):
        prev = lines[j]
        if not prev.strip():
            continue
        pind = _indent(prev)
        if pind < ind:
            key = prev.strip().lstrip("- ").split(":", 1)[0]
            if key == "if":
                return True  # continuation of a folded if: expression
            return key == "env"
    return False


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Generate .github/workflows/<name>.yml that starts a run from a label, comment command, or schedule.",
    )
    p.add_argument("--name", default=DEFAULT_NAME, help="workflow file and name (kebab-case, default %(default)s)")
    p.add_argument("--label", help="start when this label is added to an issue")
    p.add_argument("--command", help="start on an issue/PR comment that is this command, e.g. /run (owners, members, collaborators only)")
    p.add_argument("--cron", action="append", default=[], help="start on this cron schedule (UTC, 5 fields); repeatable")
    p.add_argument("--run-command", default=DEFAULT_RUN_COMMAND, help="command the run step executes (passed via env)")
    p.add_argument("--running-label", default=DEFAULT_RUNNING_LABEL, help="label that marks a run in progress (default %(default)s)")
    p.add_argument("--timeout-minutes", type=int, default=60, help="job timeout (default %(default)s)")
    p.add_argument("--repo", default=".", help="repo root to write into (default: current dir)")
    p.add_argument("--write", action="store_true", help="write the file (default: dry run, print YAML)")
    p.add_argument("--force", action="store_true", help="overwrite an existing workflow file")
    p.add_argument("--lint", metavar="PATH", help="only lint an existing workflow file for script injection")
    p.add_argument("--json", action="store_true", help="print machine JSON")
    args = p.parse_args(argv)

    if args.lint:
        try:
            with open(args.lint, encoding="utf-8") as fh:
                text = fh.read()
        except OSError as exc:
            print(f"error: cannot read {args.lint}: {exc}", file=sys.stderr)
            return 2
        problems = lint_workflow(text)
        if args.json:
            print(json.dumps({"path": args.lint, "problems": problems, "ok": not problems}, indent=2))
        elif problems:
            print(f"{args.lint}: {len(problems)} problem(s)")
            for prob in problems:
                print(f"  {prob}")
        else:
            print(f"{args.lint}: ok")
        return 1 if problems else 0

    try:
        validate(args)
        if args.timeout_minutes < 1:
            raise UsageError("--timeout-minutes must be >= 1")
    except UsageError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    text = build_workflow(
        args.name, args.label, args.command, args.cron, args.run_command, args.running_label, args.timeout_minutes
    )
    problems = lint_workflow(text)
    path = os.path.join(args.repo, ".github", "workflows", f"{args.name}.yml")
    triggers = {"label": args.label, "command": args.command, "cron": args.cron}

    written = False
    if args.write and not problems:
        if os.path.exists(path) and not args.force:
            print(f"error: {path} exists; pass --force to overwrite", file=sys.stderr)
            return 2
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        written = True

    if args.json:
        print(json.dumps(
            {"path": path, "written": written, "triggers": triggers, "problems": problems, "yaml": text},
            indent=2,
        ))
    else:
        if problems:
            print("lint problems in generated workflow (not written):", file=sys.stderr)
            for prob in problems:
                print(f"  {prob}", file=sys.stderr)
        if written:
            print(f"wrote {path}")
        else:
            sys.stdout.write(text)
            if not problems:
                print(f"# dry run: pass --write to create {path}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
