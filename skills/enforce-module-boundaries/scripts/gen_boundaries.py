#!/usr/bin/env python3
"""Generate module boundary rules from the folder layout.

TypeScript/JavaScript: a .dependency-cruiser.cjs that forbids import cycles and
imports into another module's internals (only its index file is public).
.NET: an ArchUnitNET (xUnit) test that forbids dependencies between module namespaces.

Dry run by default; --write applies. Exit codes: 0 proposed, written or already
present, 1 fewer than two modules, 2 usage error.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

DEFAULT_EXCLUDES = ["node_modules", "__tests__", "__mocks__", "test", "tests", "testing", "types",
                    "typings", "assets", "styles", "bin", "obj", "Properties"]
INDEX_RE = r"index\.(ts|tsx|js|jsx|mjs|cjs)$"
TEST_CLASS = "ModuleBoundariesTests"
TEST_FRAMEWORK_RE = re.compile(r"(?i)Microsoft\.NET\.Test\.Sdk|xunit")


def js_regex_escape(text: str) -> str:
    return re.sub(r"([.^$*+?()\[\]{}|\\])", r"\\\1", text)


def detect_stack(repo: Path) -> str | None:
    if (repo / "package.json").exists() or (repo / "tsconfig.json").exists():
        return "ts"
    if list(repo.glob("*.sln")) or list(repo.glob("*.slnx")) or list(repo.glob("**/*.csproj")):
        return "dotnet"
    return None


def find_modules(repo: Path, root: str, glob: str, excludes: list[str]) -> list[str]:
    base = (repo / root).resolve()
    if not base.is_dir():
        raise ValueError(f"--root is not a directory: {root}")
    found = []
    for path in sorted(base.glob(glob)):
        if not path.is_dir() or path.name.startswith(".") or path.name in excludes:
            continue
        found.append(path.relative_to(repo.resolve()).as_posix())
    return found


# ---------------------------------------------------------------- TypeScript

def render_depcruise(modules: list[str], has_tsconfig: bool) -> str:
    alt = "(" + "|".join(js_regex_escape(m) for m in modules) + ")"
    q = json.dumps
    lines = [
        "// Generated by enforce-module-boundaries (gen_boundaries.py). Review before committing.",
        "// Modules: " + ", ".join(modules),
        "// A module may import another module only through that module's index file.",
        "// Add a legit exception to pathNot with a comment saying why.",
        "/** @type {import('dependency-cruiser').IConfiguration} */",
        "module.exports = {",
        "  forbidden: [",
        "    {",
        '      name: "no-circular",',
        '      severity: "error",',
        '      comment: "Import cycles stop modules from changing in isolation.",',
        "      from: {},",
        "      to: { circular: true },",
        "    },",
        "    {",
        '      name: "no-cross-module-internals",',
        '      severity: "error",',
        '      comment: "Import another module only through its public index.",',
        f"      from: {{ path: {q('^' + alt + '/')} }},",
        "      to: {",
        f"        path: {q('^' + alt + '/')},",
        f"        pathNot: [{q('^$1/')}, {q('^' + alt + '/' + INDEX_RE)}],",
        "      },",
        "    },",
        "  ],",
        "  options: {",
        '    doNotFollow: { path: "node_modules" },',
        "    tsPreCompilationDeps: true,",
    ]
    if has_tsconfig:
        lines.append('    tsConfig: { fileName: "tsconfig.json" },')
    lines += ["  },", "};", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------- .NET

def csproj_namespace(proj: Path) -> str:
    try:
        text = proj.read_text(encoding="utf-8", errors="replace")
    except OSError:
        text = ""
    match = re.search(r"<RootNamespace>\s*([^<\s]+)\s*</RootNamespace>", text)
    return match.group(1) if match else proj.stem


def module_namespaces(repo: Path, root: str, modules: list[str], prefix: str | None) -> list[str]:
    base = repo / root
    if not prefix:
        projs = sorted(base.glob("*.csproj"))
        prefix = csproj_namespace(projs[0]) if projs else None
    out = []
    for mod in modules:
        projs = sorted((repo / mod).glob("*.csproj"))
        if projs:  # module is its own project
            out.append(csproj_namespace(projs[0]))
            continue
        base_parts = Path(root).parts if root not in (".", "") else ()
        parts = Path(mod).parts
        if parts[:len(base_parts)] == base_parts:
            parts = parts[len(base_parts):]
        dotted = ".".join(parts)
        out.append(f"{prefix}.{dotted}" if prefix else dotted)
    return out


def assembly_filter(namespaces: list[str]) -> str:
    first = namespaces[0].split(".")[0]
    return f"{first}*.dll"


def render_archunit(namespaces: list[str], source: str) -> str:
    mods = "\n".join(f'        "{ns}",' for ns in namespaces)
    return f"""// Generated by enforce-module-boundaries (gen_boundaries.py). Review before committing.
// Needs the TngTech.ArchUnitNET.xUnit package in this test project and project references
// to the assemblies that hold the modules. Modules found under {source}.
// ArchUnitNET 0.11+: ResideInNamespace(pattern, true) is ResideInNamespaceMatching(pattern).
using System.Collections.Generic;
using System.Linq;
using System.Text.RegularExpressions;
using ArchUnitNET.Domain;
using ArchUnitNET.Loader;
using ArchUnitNET.xUnit;
using Xunit;
using static ArchUnitNET.Fluent.ArchRuleDefinition;

namespace ModuleBoundaries;

public class {TEST_CLASS}
{{
    public static readonly string[] Modules =
    {{
{mods}
    }};

    // Allowed module-to-module dependencies as "From -> To". Each entry needs a reason comment.
    private static readonly HashSet<string> Allowed = new()
    {{
    }};

    private static readonly Architecture Architecture = new ArchLoader()
        .LoadFilteredDirectory(System.AppContext.BaseDirectory, "{assembly_filter(namespaces)}")
        .Build();

    public static IEnumerable<object[]> ModulePairs() =>
        from a in Modules
        from b in Modules
        where a != b && !Allowed.Contains($"{{a}} -> {{b}}")
        select new object[] {{ a, b }};

    [Theory]
    [MemberData(nameof(ModulePairs))]
    public void Module_must_not_depend_on_other_module(string from, string to)
    {{
        Types().That().ResideInNamespace(Pattern(from), true)
            .Should().NotDependOnAny(Types().That().ResideInNamespace(Pattern(to), true))
            .Because($"{{from}} must not reach into {{to}}")
            .Check(Architecture);
    }}

    private static string Pattern(string ns) => "^" + Regex.Escape(ns) + @"(\\..+)?$";
}}
"""


def default_dotnet_out(repo: Path) -> str:
    for proj in sorted(repo.glob("**/*.csproj")):
        if any(p in ("bin", "obj", "node_modules") for p in proj.parts):
            continue
        try:
            text = proj.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if TEST_FRAMEWORK_RE.search(text):
            return (proj.parent.relative_to(repo) / f"{TEST_CLASS}.cs").as_posix()
    return f"{TEST_CLASS}.cs"


# ---------------------------------------------------------------- main

def generate(repo: Path, stack: str, root: str, glob: str, explicit: list[str] | None,
             excludes: list[str], prefix: str | None, out: str | None) -> dict:
    modules = [Path(m).as_posix().strip("/") for m in explicit] if explicit else find_modules(repo, root, glob, excludes)
    result = {"stack": stack, "root": root, "modules": modules}
    if stack == "ts":
        result["target"] = out or ".dependency-cruiser.cjs"
        result["content"] = render_depcruise(modules, (repo / "tsconfig.json").exists()) if len(modules) >= 2 else None
    else:
        namespaces = module_namespaces(repo, root, modules, prefix)
        result["namespaces"] = namespaces
        result["target"] = out or default_dotnet_out(repo)
        result["test_filter"] = f"FullyQualifiedName~{TEST_CLASS}"
        result["content"] = render_archunit(namespaces, root) if len(modules) >= 2 else None
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate module boundary rules from the folder layout.")
    parser.add_argument("path", nargs="?", default=".", help="repo root (default: .)")
    parser.add_argument("--root", help="dir that holds the modules, relative to the repo (default: src if present, else .)")
    parser.add_argument("--modules-glob", default="*",
                        help="glob under --root that matches module dirs (default: *; e.g. features/*)")
    parser.add_argument("--module", action="append", help="explicit module dir, repo-relative (repeatable; overrides the glob)")
    parser.add_argument("--exclude", action="append", default=[], help="dir name to skip (repeatable, added to defaults)")
    parser.add_argument("--stack", choices=["auto", "ts", "dotnet"], default="auto")
    parser.add_argument("--namespace-prefix", help=".NET: namespace prefix for folder modules (default: RootNamespace of the csproj in --root)")
    parser.add_argument("--out", help="output file (default: .dependency-cruiser.cjs, or ModuleBoundariesTests.cs in the first test project)")
    parser.add_argument("--write", action="store_true", help="write the file (default: dry run)")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    parser.add_argument("--json", action="store_true", help="print machine JSON")
    args = parser.parse_args(argv)

    repo = Path(args.path).resolve()
    if not repo.is_dir():
        print(f"error: not a directory: {repo}", file=sys.stderr)
        return 2
    stack = detect_stack(repo) if args.stack == "auto" else args.stack
    if not stack:
        print("error: cannot detect stack (no package.json, tsconfig.json or .NET project); pass --stack", file=sys.stderr)
        return 2
    root = args.root or ("src" if (repo / "src").is_dir() else ".")
    try:
        result = generate(repo, stack, root, args.modules_glob, args.module, DEFAULT_EXCLUDES + args.exclude,
                          args.namespace_prefix, args.out)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    target = repo / result["target"]
    if result["content"] is None:
        result["action"] = "nothing"
        result["reason"] = f"found {len(result['modules'])} module(s); need at least 2 (check --root/--modules-glob)"
    elif target.exists() and not args.force:
        result["action"] = "exists"
        result["reason"] = f"{result['target']} exists; pass --force to overwrite or merge by hand"
    elif args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(result["content"], encoding="utf-8")
        result["action"] = "wrote"
    else:
        result["action"] = "would-write"

    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(f"stack: {stack}  root: {root}")
        print("modules: " + (", ".join(result["modules"]) or "(none)"))
        if result.get("namespaces"):
            print("namespaces: " + ", ".join(result["namespaces"]))
        if result["action"] in ("nothing", "exists"):
            print(result["reason"])
        else:
            print(f"{'wrote' if result['action'] == 'wrote' else 'would write'}: {result['target']}")
            if result["action"] == "would-write":
                print(result["content"])
                print("dry run: pass --write to apply")
    return 1 if result["action"] == "nothing" else 0


if __name__ == "__main__":
    sys.exit(main())
